#!/usr/bin/env python3
"""Convert a .po file into a data-only JS file for the Helios booth.

Usage: python3 tools/po2js.py <lang> [--po PATH] [--out PATH] [--check]

  <lang>   language code, e.g. pt_BR or es. Output uses the web form (pt-BR).
  --check  do not write; exit 1 if the output file differs from what would be written.

Output is deterministic (sorted keys). Fuzzy and empty entries are skipped.
Placeholders (%(x)s, %s, {x}) must match between msgid and msgstr.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG_RE = re.compile(r'^[A-Za-z]{2,3}([_-][A-Za-z0-9]{2,8})?$')
PLACEHOLDER_RE = re.compile(r'%\([A-Za-z_][A-Za-z0-9_]*\)[sd]|%[sd]|\{[A-Za-z_][A-Za-z0-9_]*\}')
HEADER = "// GENERATED by tools/po2js.py from the .po file. Do not edit. Data only.\n"


class PoError(Exception):
    pass


def _unquote(line, lineno):
    line = line.strip()
    if len(line) < 2 or line[0] != '"' or line[-1] != '"':
        raise PoError("line %d: bad string: %r" % (lineno, line))
    return json.loads(line)  # .po escapes are a subset of JSON escapes


def parse_po(text):
    """Return list of (msgid, msgstr, fuzzy). Skips header, plurals and msgctxt entries."""
    entries = []
    cur = {}
    field = None
    flags = ""

    def flush():
        nonlocal cur, field, flags
        if "msgid" in cur and "msgstr" in cur and "msgid_plural" not in cur and "msgctxt" not in cur:
            entries.append((cur["msgid"], cur["msgstr"], "fuzzy" in flags))
        cur, field, flags = {}, None, ""

    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            flush()
        elif line.startswith("#,"):
            flags += line
        elif line.startswith("#"):
            continue
        elif line.startswith('"'):
            if field is None:
                raise PoError("line %d: string without field" % n)
            cur[field] += _unquote(line, n)
        else:
            m = re.match(r'^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")$', line)
            if not m:
                raise PoError("line %d: cannot parse: %r" % (n, line))
            name = m.group(1)
            if name.startswith("msgstr[") or name == "msgid_plural":
                field = "msgid_plural" if name == "msgid_plural" else "plural_str"
                cur.setdefault(field, "")
                cur[field] += _unquote(m.group(2), n)
                continue
            if name == "msgid" and "msgstr" in cur:
                flush()
            field = name
            cur[field] = _unquote(m.group(2), n)
    flush()
    return entries


def build_strings(entries):
    out = {}
    for msgid, msgstr, fuzzy in entries:
        if not msgid or not msgstr or fuzzy:
            continue
        if sorted(PLACEHOLDER_RE.findall(msgid)) != sorted(PLACEHOLDER_RE.findall(msgstr)):
            raise PoError("placeholder mismatch: %r -> %r" % (msgid, msgstr))
        out[msgid] = msgstr
    return out


def render(strings):
    body = json.dumps(strings, ensure_ascii=False, sort_keys=True, indent=1)
    # keep the file inert if viewed as HTML or concatenated
    body = body.replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return HEADER + "BOOTH_STRINGS = " + body + ";\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("lang")
    ap.add_argument("--po")
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if not LANG_RE.match(a.lang):
        ap.error("invalid language code: %r" % a.lang)
    web = a.lang.replace("_", "-")
    po = Path(a.po) if a.po else ROOT / "locale" / a.lang / "LC_MESSAGES" / "booth.po"
    out = Path(a.out) if a.out else ROOT / "heliosbooth" / "js" / ("strings.%s.js" % web)
    try:
        content = render(build_strings(parse_po(po.read_text(encoding="utf-8"))))
    except (PoError, OSError) as e:
        print("error: %s" % e, file=sys.stderr)
        return 2
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != content:
            print("out of date: %s" % out, file=sys.stderr)
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
